"""
Persistence manager for loading download state from temp file headers
"""
import json
import os
import glob
from typing import List, Dict, Any
from urllib.parse import urlparse

# Metadata header size (bytes) - must match download_engine.py
METADATA_HEADER_SIZE = 4096


class PersistenceManager:
    """Manages loading of download state from temp file headers."""

    def save_downloads(self, downloads_data: List[Dict[str, Any]]) -> bool:
        """Download state is now saved in temp file headers - no separate state file needed."""
        # This method is kept for API compatibility but does nothing
        # Metadata is saved in each temp file's header by the download engine
        return True

    def load_downloads(self) -> List[Dict[str, Any]]:
        """Load download state by scanning for .temp files and reading their metadata headers."""
        downloads_data = []

        # Get default downloads directory
        downloads_dir = os.path.expanduser("~")

        # Try to get Downloads folder from system
        try:
            # Windows-specific: get Downloads folder
            if os.name == 'nt':
                import ctypes
                from ctypes import wintypes
                CSIDL_DOWNLOADS = 0x0B  # GUID for Downloads folder
                SHGFP_TYPE_CURRENT = 0

                buf = ctypes.create_unicode_buffer(wintypes.MAX_PATH)
                ctypes.windll.shell32.SHGetFolderPathW(0, CSIDL_DOWNLOADS, 0, SHGFP_TYPE_CURRENT, buf)
                downloads_dir = buf.value
        except Exception:
            pass

        # Also check current directory
        search_dirs = [downloads_dir, os.getcwd()]

        for search_dir in search_dirs:
            if not os.path.isdir(search_dir):
                continue

            # Scan for .temp files
            temp_files = glob.glob(os.path.join(search_dir, "*.temp"))

            for temp_file in temp_files:
                try:
                    metadata = self._read_temp_file_metadata(temp_file)
                    if metadata:
                        # Extract download info from metadata
                        download_data = {
                            'download_id': '',  # Will be generated by DownloadItem
                            'url': metadata.get('url', ''),
                            'save_path': self._derive_save_path_from_temp(temp_file, metadata),
                            'speed_limit': 0,
                            'status': 'paused',  # Default to paused on restore
                            'downloaded_bytes': metadata.get('downloaded_bytes', 0),
                            'total_bytes': metadata.get('file_size', -1),
                            'error_message': '',
                            'referrer': '',
                            'cookies': '',
                            'user_agent': '',
                            'post_data': '',
                            'document_url': '',
                            'temp_file': temp_file
                        }
                        downloads_data.append(download_data)
                        print(f"Found download in temp file: {temp_file}")
                except Exception as e:
                    print(f"Error reading temp file {temp_file}: {e}")
                    continue

        print(f"Loaded {len(downloads_data)} downloads from temp file headers")
        return downloads_data

    def _read_temp_file_metadata(self, temp_file: str) -> Dict[str, Any]:
        """Read metadata from temp file header."""
        try:
            if not os.path.exists(temp_file):
                return {}

            with open(temp_file, 'rb') as f:
                header = f.read(METADATA_HEADER_SIZE)

            # Trim null bytes and decode
            header = header.rstrip(b'\x00').decode('utf-8')

            if not header or not header.startswith('{'):
                return {}

            return json.loads(header)
        except Exception as e:
            print(f"Error reading metadata from {temp_file}: {e}")
            return {}

    def _derive_save_path_from_temp(self, temp_file: str, metadata: Dict[str, Any]) -> str:
        """Derive the final save path from temp file and metadata."""
        # Try to get the output file from the temp file's directory
        # Since temp files are named with hash, we need to reconstruct the original filename
        # For now, we'll use a simple approach: temp_file without .temp extension
        # The DownloadItem will handle unique filename generation if needed

        # Get the directory
        temp_dir = os.path.dirname(temp_file)

        # Try to extract filename from URL if available
        url = metadata.get('url', '')
        if url:
            parsed = urlparse(url)
            filename = os.path.basename(parsed.path)
            if filename:
                return os.path.join(temp_dir, filename)

        # Fallback: use temp file name without .temp
        base_name = os.path.basename(temp_file)
        return os.path.join(temp_dir, base_name.replace('.temp', ''))

    def clear_state(self) -> bool:
        """Clear saved download state - no longer needed as state is in temp files."""
        # This method is kept for API compatibility but does nothing
        # Temp files are cleaned up when downloads are removed
        return True
